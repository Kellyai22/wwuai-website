#!/usr/bin/env node
// Writes assets/system/tokens.css from the brand's single colour source,
// ~/.claude/wwuai-os/config/brand-tokens.json. Never edit tokens.css by hand.
//   node scripts/build-tokens.mjs           write the file
//   node scripts/build-tokens.mjs --check   exit 1 if the committed file has drifted
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = process.env.BRAND_TOKENS || path.join(os.homedir(), ".claude/wwuai-os/config/brand-tokens.json");
const out = path.join(root, "assets/system/tokens.css");

const tokens = JSON.parse(fs.readFileSync(src, "utf8"));
const p = tokens.palette;
for (const k of ["pearl", "greige", "bordeaux", "blush"]) {
  if (!p[k] || !/^#[0-9A-Fa-f]{6}$/.test(p[k].hex)) throw new Error(`brand-tokens.json: palette.${k}.hex missing or not a 6-digit hex`);
}
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(" ");

const css = `/* GENERATED by scripts/build-tokens.mjs from brand-tokens.json (version ${tokens.version}).
   Do not edit. Change the brand file, then run: node scripts/build-tokens.mjs */
:root {
  --pearl: ${p.pearl.hex};
  --greige: ${p.greige.hex};
  --bordeaux: ${p.bordeaux.hex};
  --blush: ${p.blush.hex};
  --pearl-rgb: ${rgb(p.pearl.hex)};
  --greige-rgb: ${rgb(p.greige.hex)};
  --bordeaux-rgb: ${rgb(p.bordeaux.hex)};
  --blush-rgb: ${rgb(p.blush.hex)};
  --muted: rgb(var(--bordeaux-rgb) / ${p.muted?.alpha ?? 0.65});
  --line: rgb(var(--bordeaux-rgb) / ${p.line?.alpha ?? 0.12});
  --muted-on-dark: rgb(var(--pearl-rgb) / .74);
  --line-on-dark: rgb(var(--pearl-rgb) / .16);
}
/* Registered so a section's whole tone (background, type, rules) can fade together. */
${[
  ["bg", p.pearl.hex], ["paper", p.greige.hex], ["ink", p.bordeaux.hex], ["em", p.bordeaux.hex],
  ["soft", `rgb(${rgb(p.bordeaux.hex)} / ${p.muted?.alpha ?? 0.65})`],
  ["rule", `rgb(${rgb(p.bordeaux.hex)} / ${p.line?.alpha ?? 0.12})`],
].map(([n, v]) => `@property --${n} { syntax: "<color>"; inherits: true; initial-value: ${v}; }`).join("\n")}
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current !== css) { console.error("tokens.css is out of date with brand-tokens.json. Run: node scripts/build-tokens.mjs"); process.exit(1); }
  console.log("tokens.css matches brand-tokens.json");
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, css);
  console.log(`wrote ${path.relative(root, out)}`);
}
